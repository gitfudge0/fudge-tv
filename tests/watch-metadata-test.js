'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const nav=require('../app/src/main/assets/ui/navigation.js');
const source=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/ui/app.js'),'utf8');
const production=name=>{const line=source.split('\n').find(line=>line.startsWith(`function ${name}(`));assert.ok(line);return line;};
const program={id:'watch:app:42',title:'Resident Alien',season:1,episode:2};
const sparse={key:'series:tt8690918',mediaType:'series',title:program.title,overview:'',art:'https://images.metahub.space/background/medium/tt8690918/img'};
const calls=[],enrichment=new Map();
const state={queue:[program],watchHero:{...program,description:'Original shared synopsis',art:'/art/original'}};
let renders=0;
const context={state,enrichment,FudgeNav:nav,$:()=>null,renderHero:()=>renders++,native:(op,data)=>calls.push({op,...data})};
vm.createContext(context);
vm.runInContext(['applyWatchMetadata','nativeEvent'].map(production).join('\n'),context);
function deliver(items,extra={}){context.nativeEvent('watchMetadata',{id:program.id,title:program.title,items,...extra});}
deliver([sparse]);
assert.equal(calls.length,1);assert.equal(calls[0].key,sparse.key);assert.equal(calls[0].id,program.id);
assert.equal(state.watchHero.description,'Original shared synopsis');assert.equal(state.watchHero.art,sparse.art);
deliver([sparse]);assert.equal(calls.length,1);
const before=enrichment.get(program.id),rendersBefore=renders;
deliver([{...sparse,overview:'Wrong key description',key:'series:tt1234567'}],{enriched:true});
deliver([{...sparse,overview:'Wrong title description'}],{title:'Other title',enriched:true});
deliver([{...sparse,overview:'Wrong program description'}],{id:'watch:app:wrong',enriched:true});
assert.equal(enrichment.get(program.id),before);assert.equal(renders,rendersBefore);
deliver([],{enriched:true});
assert.equal(state.watchHero.art,sparse.art);assert.equal(state.watchHero.description,'Original shared synopsis');assert.equal(calls.length,1);
deliver([{...sparse,overview:'An alien hides in a small Colorado town.'}],{enriched:true});
assert.equal(state.watchHero.description,'An alien hides in a small Colorado town.');assert.equal(calls.length,1);
// A movie of the same name cannot enrich a program carrying season/episode data.
enrichment.clear();calls.length=0;
const priorDescription=state.watchHero.description,priorArt=state.watchHero.art;
deliver([{...sparse,key:'movie:tt1234567',mediaType:'movie',overview:'Wrong movie'}]);
assert.equal(state.watchHero.description,priorDescription);assert.equal(state.watchHero.art,priorArt);assert.equal(calls.length,0);
deliver([sparse,{...sparse,key:'series:tt1234567'}]);
assert.equal(calls.length,0);assert.equal(state.watchHero.description,priorDescription);
console.log('Watch metadata: sparse unique follow-up once, enriched synopsis, id/title/key guards, failed detail artwork retention and ambiguous/episodic matching passed');
